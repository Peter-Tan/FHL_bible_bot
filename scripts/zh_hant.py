"""
zh_hant.py — 把答案裡零星漏出的簡體字轉回繁體（narrow, table-driven）.

Why this exists
---------------
The v4 system prompt already says「Output language: 繁體中文 (zh-tw)」, yet a
scan of logs/chat.db (2026-04-30 → 2026-08-13) found 8 of 288 assistant
answers (~2.8%) with simplified characters mixed INTO otherwise correct
繁體 sentences — 「核心问题」「强调」「①银子作为在众人眼前证明…」— concentrated
in long 原文分析 answers. One of them (msg 488) also leaked Russian
(「инфинитив绝对式」), which points at multilingual token bleed under long
context rather than a prompt bug. Prompt wording alone is not holding, so the
fix is deterministic post-processing.

Why NOT plain OpenCC
--------------------
Measured over the same 288 answers:
  - OpenCC s2t   rewrote 114/288 messages — 吃→喫 (116x), 群→羣 (63x),
    才→纔 (29x), 里→裏, 台→臺, 祢→禰 … i.e. it mangles correct Traditional text.
  - OpenCC s2twp rewrote 168/288 — additionally swapping vocabulary
    (對象→物件, 信息→資訊) and deleting characters outright.
For a tool that quotes 和合本 verbatim that trade is unacceptable: 114 damaged
messages to repair 8.

What this does instead
----------------------
A pure character table (2,475 entries), restricted to codepoints that are
(1) not encodable in Big5, (2) left unchanged by OpenCC t2s — so not a
Traditional variant either — and (3) mapped by OpenCC s2tw to exactly one
other character. Regenerate with scripts/gen_zh_hant_table.py; the table is
committed so the server needs no OpenCC dependency at runtime.

Rule (2) matters as much as (1): 裏 is Traditional but absent from Big5, and
和合本 uses both 裏 and 裡 — rewriting it would edit quoted scripture. Same for
麽 and 衆.

Validated against all 288 answers: it alters exactly the 8 real cases and
nothing else (祢 is on the KEEP list in the generator — it is the Christian
honorific 「願祢的旨意成就」, not a simplified form).

Cost: str.translate over the largest answer ever logged (10,149 chars) is
0.9 ms, in the worker thread AFTER streaming has finished — it cannot affect
time-to-first-token or the streaming rate.

Known limitation: 121 of the entries are one-to-many in principle
(发→發/髮, 别→別/彆, 历→曆/歷) and a character table always picks the common
form, so a hypothetical 头发 would become 頭發, not 頭髮. None of these
appeared in four months of traffic; if one ever does, the fix is phrase-aware
conversion of the affected span, not a wider table.
"""

